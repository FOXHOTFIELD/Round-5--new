// 常量与工具函数声明（放入头文件保护内）
#ifndef M_PI
#define M_PI 3.14159265358979323846f
#endif

// 输入：单位四元数 q0..q3
// 输出：yaw/pitch/roll（弧度）
void quat_to_euler_zyx(float q0, float q1, float q2, float q3,
                       float* yaw, float* pitch, float* roll);

