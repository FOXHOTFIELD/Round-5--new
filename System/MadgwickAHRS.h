#ifndef MadgwickAHRS_h
#define MadgwickAHRS_h

//----------------------------------------------------------------------------------------------------
// Variable declaration（全局变量声明）

extern volatile float beta;				// 算法增益（2*Kp）。数值越大越相信加速度/磁力计，收敛更快但动态下可能抖。
extern volatile float q0, q1, q2, q3;	// 姿态四元数（传感器坐标系相对于参考坐标系的旋转）。
extern float yaw, pitch , roll ;

//---------------------------------------------------------------------------------------------------
// Function declarations（函数声明）

// 完整融合（含磁力计）：当磁力计有效时调用，可估计绝对航向。
void MadgwickAHRSupdate(float gx, float gy, float gz, float ax, float ay, float az, float mx, float my, float mz);

// 仅 IMU 融合（无磁力计）：航向不可观（仅相对变化），适用于磁力计不可用或失效的场景。
void MadgwickAHRSupdateIMU(float gx, float gy, float gz, float ax, float ay, float az);

/* 运行时设置采样频率（Hz）。
 * 注意：应与姿态更新任务的实际循环频率一致，例如 100/200/250/500Hz。
 */
void MadgwickAHRS_SetSampleFreq(float hz);

// 三角函数近似模式配置（运行时可切换）
#define TRIG_STD  0
#define TRIG_LUT  1
#define TRIG_POLY 2
void set_trig_approx_mode(int mode);



#endif
